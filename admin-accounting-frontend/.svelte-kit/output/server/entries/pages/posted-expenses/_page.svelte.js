import { c as create_ssr_component, s as subscribe, v as validate_component } from "../../../chunks/ssr.js";
import { P as PageHeader, f as formatCurrency } from "../../../chunks/formatters.js";
import { D as DataTable } from "../../../chunks/DataTable.js";
import { R as RowActions } from "../../../chunks/RowActions.js";
import { S as StatCard } from "../../../chunks/StatCard.js";
import { E as ExpenseDetailModal } from "../../../chunks/ExpenseDetailModal.js";
import { l as expenses } from "../../../chunks/dataStore.js";
import { e as expenseTypeLabel } from "../../../chunks/accounting-options.js";
import { d as dateColumn, c as currencyColumn } from "../../../chunks/tableColumns.js";
const PostedExpensesView = create_ssr_component(($$result, $$props, $$bindings, slots) => {
  let posted;
  let postedTotals;
  let $expenses, $$unsubscribe_expenses;
  $$unsubscribe_expenses = subscribe(expenses, (value) => $expenses = value);
  let isDetailOpen = false;
  let detailExpense = null;
  const columns = [
    dateColumn("date", "Expense Date"),
    {
      key: "expenseNo",
      label: "Expense No",
      sortable: true
    },
    {
      key: "expenseType",
      label: "Type",
      sortable: true,
      format: (value) => expenseTypeLabel(value)
    },
    {
      key: "departmentName",
      label: "Department",
      sortable: true
    },
    {
      key: "accountCode",
      label: "COA",
      sortable: true
    },
    currencyColumn("totalAmount", "Total"),
    dateColumn("postedAt", "Posted At"),
    {
      key: "glReference",
      label: "GL Reference"
    }
  ];
  function openDetail(expense) {
    detailExpense = expense;
    isDetailOpen = true;
  }
  let $$settled;
  let $$rendered;
  let previous_head = $$result.head;
  do {
    $$settled = true;
    $$result.head = previous_head;
    posted = $expenses.filter((expense) => expense.status === "posted");
    postedTotals = posted.reduce(
      (totals, expense) => ({
        total: totals.total + expense.totalAmount,
        salary: totals.salary + (expense.expenseType === "salary" ? expense.totalAmount : 0),
        tax: totals.tax + expense.taxAmount
      }),
      { total: 0, salary: 0, tax: 0 }
    );
    $$rendered = `<div class="space-y-6">${validate_component(PageHeader, "PageHeader").$$render(
      $$result,
      {
        title: "Posted Expenses",
        description: "Expenses that have been posted to the general ledger. Journal references are generated by the backend."
      },
      {},
      {}
    )} <div class="grid grid-cols-1 sm:grid-cols-3 gap-4">${validate_component(StatCard, "StatCard").$$render(
      $$result,
      {
        title: "Total Posted",
        value: formatCurrency(postedTotals.total),
        icon: "📘",
        color: "blue",
        hint: `${posted.length} posted expense entries`
      },
      {},
      {}
    )} ${validate_component(StatCard, "StatCard").$$render(
      $$result,
      {
        title: "Salary Posted",
        value: formatCurrency(postedTotals.salary),
        icon: "👔",
        color: "purple",
        hint: "Employee salary posted to GL"
      },
      {},
      {}
    )} ${validate_component(StatCard, "StatCard").$$render(
      $$result,
      {
        title: "Tax Posted",
        value: formatCurrency(postedTotals.tax),
        icon: "🧾",
        color: "yellow",
        hint: "Input tax from posted expenses"
      },
      {},
      {}
    )}</div> ${validate_component(DataTable, "DataTable").$$render(
      $$result,
      {
        columns,
        data: posted,
        searchKeys: [
          "expenseNo",
          "expenseType",
          "departmentName",
          "accountCode",
          "glReference"
        ],
        searchPlaceholder: "Search posted expense or GL reference...",
        emptyMessage: "No posted expenses yet"
      },
      {},
      {
        actions: ({ row }) => {
          return `${validate_component(RowActions, "RowActions").$$render(
            $$result,
            {
              onView: () => openDetail(row),
              viewTitle: "View posted expense"
            },
            {},
            {}
          )}`;
        }
      }
    )}</div> ${validate_component(ExpenseDetailModal, "ExpenseDetailModal").$$render(
      $$result,
      {
        expense: detailExpense,
        isOpen: isDetailOpen
      },
      {
        isOpen: ($$value) => {
          isDetailOpen = $$value;
          $$settled = false;
        }
      },
      {}
    )}`;
  } while (!$$settled);
  $$unsubscribe_expenses();
  return $$rendered;
});
const Page = create_ssr_component(($$result, $$props, $$bindings, slots) => {
  return `${validate_component(PostedExpensesView, "PostedExpensesView").$$render($$result, {}, {}, {})}`;
});
export {
  Page as default
};
