CREATE TABLE transaction_quotation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_number  VARCHAR(50) NOT NULL UNIQUE,
    transaction_number VARCHAR(50) NOT NULL,
    document_date    DATE NOT NULL,
    valid_until      DATE,
    customer_id      BIGINT NOT NULL REFERENCES masterdata_customer(id),
    salesperson_id   BIGINT REFERENCES masterdata_employee(id),
    prepared_by      BIGINT REFERENCES masterdata_user(id),
    payment_term_id  BIGINT REFERENCES masterdata_payment_term(id),
    tax_rate_id      BIGINT REFERENCES masterdata_tax_rate(id),
    currency_code    CHAR(3) NOT NULL DEFAULT 'IDR',
    exchange_rate    NUMERIC(18,6) NOT NULL DEFAULT 1 CHECK (exchange_rate > 0),
    subtotal         NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (subtotal >= 0),
    discount_total   NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (discount_total >= 0),
    tax_total        NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (tax_total >= 0),
    shipping_cost    NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (shipping_cost >= 0),
    grand_total      NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (grand_total >= 0),
    status           VARCHAR(20) NOT NULL DEFAULT 'draft'
                     CHECK (status IN ('draft', 'created', 'approved', 'rejected', 'pending', 'completed', 'reopen')),
    notes            TEXT,
    approved_by      BIGINT REFERENCES masterdata_user(id),
    approved_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (valid_until IS NULL OR valid_until >= document_date)
);

