CREATE OR REPLACE VIEW report_general_ledger AS
SELECT
    j.id AS journal_id,
    j.journal_number,
    j.journal_date AS date,
    coa.account_code,
    coa.account_name,
    jd.description,
    jd.debit,
    jd.credit,
    (jd.debit - jd.credit) AS balance,
    j.reference_type,
    j.reference_id
