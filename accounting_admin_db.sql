-- Immutable report snapshots. When a period is closed, the report generator
-- writes the final report payload and its tabular lines here. Reports for a
-- closed period must be read from this snapshot, never recalculated from live
-- journals, so later corrections cannot move historical numbers.
CREATE TABLE report_snapshot (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_number VARCHAR(50)  NOT NULL UNIQUE,
    report_code     VARCHAR(50)  NOT NULL,
    report_name     VARCHAR(150) NOT NULL,
    period_id       BIGINT       NOT NULL REFERENCES accounting_period(id),
    closing_id      BIGINT REFERENCES accounting_period_closing(id),
    as_of_date      DATE         NOT NULL,
    version         INTEGER      NOT NULL DEFAULT 1 CHECK (version > 0),
    status          VARCHAR(20)  NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft', 'final', 'void')),
    parameters      JSONB        NOT NULL DEFAULT '{}'::jsonb,
    payload         JSONB        NOT NULL DEFAULT '{}'::jsonb,
    checksum        TEXT,
    generated_by    BIGINT REFERENCES masterdata_user(id),
    generated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    notes           TEXT,
    UNIQUE (report_code, period_id, version)
);

CREATE TABLE report_snapshot_line (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id  BIGINT NOT NULL REFERENCES report_snapshot(id) ON DELETE CASCADE,
    line_number  INTEGER NOT NULL CHECK (line_number > 0),
    section      VARCHAR(100),
    line_type    VARCHAR(30) NOT NULL DEFAULT 'detail'
                 CHECK (line_type IN ('header', 'detail', 'subtotal', 'total', 'note')),
    account_code VARCHAR(20),
    account_name VARCHAR(150),
    label        VARCHAR(255),
    debit        NUMERIC(18,2) NOT NULL DEFAULT 0,
    credit       NUMERIC(18,2) NOT NULL DEFAULT 0,
    amount       NUMERIC(18,2) NOT NULL DEFAULT 0,
    metadata     JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (snapshot_id, line_number)
);

-- A final snapshot is immutable. Build the header and lines as draft, then
-- change the header status to final inside the closing transaction.
CREATE OR REPLACE FUNCTION fn_block_final_report_snapshot()
RETURNS TRIGGER AS $$
BEGIN
    IF OLD.status = 'final' THEN
        RAISE EXCEPTION 'Report snapshot % is final and immutable', OLD.snapshot_number;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_report_snapshot_immutable
BEFORE UPDATE OR DELETE ON report_snapshot
FOR EACH ROW EXECUTE FUNCTION fn_block_final_report_snapshot();

CREATE OR REPLACE FUNCTION fn_block_final_snapshot_line()
RETURNS TRIGGER AS $$
DECLARE
    parent_id     BIGINT;
    parent_status VARCHAR(20);
BEGIN
    parent_id := CASE WHEN TG_OP = 'DELETE' THEN OLD.snapshot_id ELSE NEW.snapshot_id END;
    SELECT status INTO parent_status FROM report_snapshot WHERE id = parent_id;

    IF parent_status = 'final' THEN
        RAISE EXCEPTION 'Lines of final report snapshot % are immutable', parent_id;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_report_snapshot_line_immutable
BEFORE INSERT OR UPDATE OR DELETE ON report_snapshot_line
FOR EACH ROW EXECUTE FUNCTION fn_block_final_snapshot_line();

