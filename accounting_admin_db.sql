-- ============================================================================
-- ERP Accounting + HRMIS - PostgreSQL schema
-- Target: PostgreSQL 15+
--
-- Naming convention:
--   masterdata_*   master/reference data
--   transaction_*  sales and purchasing documents (header + detail)
--   inventory_*    stock movement, adjustment, balance, valuation
--   accounting_*   general ledger, expense, reconciliation, period closing
--   budget_*       annual plan, allocation, revision
--   hrm_*          attendance, payroll, statutory, salary, claim, advance
--   report_snapshot* immutable report output for closed periods
--
--   Audit events are stored in MongoDB. There is no PostgreSQL audit table;
--   a legacy audit_log table is dropped during a clean rebuild.
--
--   Every transaction workflow uses exactly these statuses:
--   draft, created, approved, rejected, pending, completed, reopen
--
-- Important:
--   The legacy single `transaksi` table is intentionally replaced by one
--   header table and one detail table per business document. A quotation,
--   sales order, delivery, invoice, receipt, purchase order, goods receipt,
--   purchase invoice, vendor payment, return, journal, payroll, etc. each has
--   its own transaction table.
--
--   Legacy transaction rows are not copied 1:1 because the old `transaksi`
--   table mixed multiple document types. Master data below is seeded from the
--   legacy dump; transactions should be rebuilt through the new flow.
-- ============================================================================

BEGIN;

-- Drop report views first (they depend on the tables below).
DO $$
DECLARE
    view_name text;
BEGIN
    FOR view_name IN
        SELECT viewname
        FROM pg_views
        WHERE schemaname = 'public'
          AND viewname LIKE 'report_%'
    LOOP
        EXECUTE format('DROP VIEW IF EXISTS %I CASCADE', view_name);
    END LOOP;
END $$;

-- Drop the new module tables and the old MySQL dump tables if they exist.
DO $$
DECLARE
    table_name text;
BEGIN
    FOR table_name IN
        SELECT tablename
        FROM pg_tables
        WHERE schemaname = 'public'
          AND (
              tablename LIKE 'masterdata_%'
              OR tablename LIKE 'transaction_%'
              OR tablename LIKE 'inventory_%'
              OR tablename LIKE 'accounting_%'
              OR tablename LIKE 'budget_%'
              OR tablename LIKE 'hrm_%'
              OR tablename IN (
                  'audit_log', 'report_snapshot', 'report_snapshot_line',
                  'akun', 'detail_penerimaan_barang', 'detail_transaksi_pembayaran',
                  'detail_transaksi_pembelian', 'detail_transaksi_penawaran',
                  'detail_transaksi_pengiriman', 'detail_transaksi_penjualan',
                  'jurnal', 'pelanggan', 'pemasok', 'pembantu_penawaran',
                  'pembayaran', 'pembayaranvendor', 'pembelian', 'penawaran',
                  'penerimaan_barang', 'pengguna', 'pengiriman', 'penjualan',
                  'produk', 'tagihan', 'transaksi'
              )
          )
    LOOP
        EXECUTE format('DROP TABLE IF EXISTS %I CASCADE', table_name);
    END LOOP;
END $$;

