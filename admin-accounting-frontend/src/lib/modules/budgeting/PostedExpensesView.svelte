<script lang="ts">
	import PageHeader from '$lib/components/ui/PageHeader.svelte';
	import DataTable from '$lib/components/ui/DataTable.svelte';
	import RowActions from '$lib/components/ui/RowActions.svelte';
	import StatCard from '$lib/components/ui/StatCard.svelte';
	import ExpenseDetailModal from './ExpenseDetailModal.svelte';
	import { expenses } from '$lib/stores/dataStore';
	import { expenseTypeLabel } from '$lib/data/accounting-options';
	import { formatCurrency } from '$lib/utils/formatters';
	import { currencyColumn, dateColumn } from '$lib/utils/tableColumns';
	import type { ExpenseEntry, ExpenseType, TableColumn } from '$lib/types';

	let isDetailOpen = false;
	let detailExpense: ExpenseEntry | null = null;

	const columns: TableColumn[] = [
		dateColumn('date', 'Expense Date'),
		{ key: 'expenseNo', label: 'Expense No', sortable: true },
		{ key: 'expenseType', label: 'Type', sortable: true, format: (value) => expenseTypeLabel(value as ExpenseType) },
		{ key: 'departmentName', label: 'Department', sortable: true },
		{ key: 'accountCode', label: 'COA', sortable: true },
		currencyColumn('totalAmount', 'Total'),
		dateColumn('postedAt', 'Posted At'),
		{ key: 'glReference', label: 'GL Reference' }
	];

	$: posted = $expenses.filter((expense) => expense.status === 'posted');
	$: postedTotals = posted.reduce(
		(totals, expense) => ({
			total: totals.total + expense.totalAmount,
			salary: totals.salary + (expense.expenseType === 'salary' ? expense.totalAmount : 0),
			tax: totals.tax + expense.taxAmount
		}),
		{ total: 0, salary: 0, tax: 0 }
	);

	function openDetail(expense: ExpenseEntry) {
		detailExpense = expense;
		isDetailOpen = true;
	}
</script>

<div class="space-y-6">
	<PageHeader
		title="Posted Expenses"
		description="Expenses that have been posted to the general ledger. Journal references are generated by the backend."
	/>

	<div class="grid grid-cols-1 sm:grid-cols-3 gap-4">
		<StatCard title="Total Posted" value={formatCurrency(postedTotals.total)} icon="📘" color="blue" hint={`${posted.length} posted expense entries`} />
		<StatCard title="Salary Posted" value={formatCurrency(postedTotals.salary)} icon="👔" color="purple" hint="Employee salary posted to GL" />
		<StatCard title="Tax Posted" value={formatCurrency(postedTotals.tax)} icon="🧾" color="yellow" hint="Input tax from posted expenses" />
	</div>

	<DataTable
		columns={columns}
		data={posted}
		searchKeys={['expenseNo', 'expenseType', 'departmentName', 'accountCode', 'glReference']}
		searchPlaceholder="Search posted expense or GL reference..."
		emptyMessage="No posted expenses yet"
	>
		<svelte:fragment slot="actions" let:row>
			<RowActions onView={() => openDetail(row)} viewTitle="View posted expense" />
		</svelte:fragment>
	</DataTable>
</div>

<ExpenseDetailModal bind:isOpen={isDetailOpen} expense={detailExpense} />
