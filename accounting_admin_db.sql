CREATE TABLE accounting_period (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_code VARCHAR(7)  NOT NULL UNIQUE,
    start_date  DATE        NOT NULL,
    end_date    DATE        NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'open'
                CHECK (status IN ('open', 'closed')),
    closed_by   BIGINT REFERENCES masterdata_user(id),
    closed_at   TIMESTAMPTZ,
    notes       TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (start_date <= end_date)
);

CREATE TABLE accounting_journal (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_number VARCHAR(50)  NOT NULL UNIQUE,
    journal_date   DATE         NOT NULL,
    journal_type   VARCHAR(30)  NOT NULL
                   CHECK (journal_type IN ('manual', 'sales', 'purchase', 'payment', 'expense', 'payroll', 'inventory', 'closing')),
    period_id      BIGINT REFERENCES accounting_period(id),
    reference_type VARCHAR(50),
    reference_id   BIGINT,
    description    TEXT,
    total_debit    NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (total_debit >= 0),
    total_credit   NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (total_credit >= 0),
    status         VARCHAR(20)  NOT NULL DEFAULT 'draft'
                   CHECK (status IN ('draft', 'created', 'approved', 'rejected', 'pending', 'completed', 'reopen')),
    posted_by      BIGINT REFERENCES masterdata_user(id),
    posted_at      TIMESTAMPTZ,
    created_by     BIGINT REFERENCES masterdata_user(id),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (total_debit = total_credit)
);

CREATE TABLE accounting_journal_detail (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_id    BIGINT NOT NULL REFERENCES accounting_journal(id) ON DELETE CASCADE,
    line_number   INTEGER NOT NULL CHECK (line_number > 0),
    coa_id        BIGINT NOT NULL REFERENCES masterdata_coa(id),
    description   TEXT,
    debit         NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
    credit        NUMERIC(18,2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
    department_id BIGINT REFERENCES masterdata_department(id),
    cost_center_id BIGINT REFERENCES masterdata_cost_center(id),
    employee_id   BIGINT REFERENCES masterdata_employee(id),
    tax_rate_id   BIGINT REFERENCES masterdata_tax_rate(id),
    UNIQUE (journal_id, line_number),
    CHECK ((debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0))
);

