-- Temporary report lock.
--
-- Financial reports stay realtime until a period is locked. Locking stores the
-- current report payload so the figures cannot change while the period is
-- being reviewed. Unlocking removes the row and returns the report to realtime.
-- This is intentionally separate from the immutable report_snapshot tables.

CREATE TABLE IF NOT EXISTS report_lock (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_code VARCHAR(50) NOT NULL,
    period      VARCHAR(7)  NOT NULL CHECK (period ~ '^[0-9]{4}-[0-9]{2}$'),
    as_of_date  DATE        NOT NULL,
    payload     JSONB       NOT NULL DEFAULT '[]'::jsonb,
    locked_by   BIGINT REFERENCES masterdata_user(id),
    locked_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    notes       TEXT,
    UNIQUE (report_code, period)
);

CREATE INDEX IF NOT EXISTS idx_report_lock_period ON report_lock(period);
CREATE INDEX IF NOT EXISTS idx_report_lock_report ON report_lock(report_code);
